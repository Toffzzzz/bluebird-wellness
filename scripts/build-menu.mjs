// Where the menu itself says "Blue Bird Wellness" (the site's own name is SITE_NAME).
function findText(value, needle, path = '') {
  if (typeof value === 'string') return value.includes(needle) ? [path] : [];
  if (Array.isArray(value)) return value.flatMap((v, i) => findText(v, needle, `${path}.${value[i]?.slug || i}`));
  if (value && typeof value === 'object') return Object.entries(value).flatMap(([k, v]) => findText(v, needle, path ? `${path}.${k}` : k));
  return [];
}
