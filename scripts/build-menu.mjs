const BLOCK = /<\/?(p|div|li|br|tr|td|th|caption|summary|h[1-6])\b[^>]*>/gi;

const decode = (text) => text
  .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
  .replace(/&(amp|lt|gt|quot|apos|nbsp);/g, (_, n) => ({ amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' })[n]);
const collapse = (text) => String(text).replace(/\s+/g, ' ').trim();
const textOf = (html) => collapse(decode(html.replace(/<!--[\s\S]*?-->/g, '').replace(BLOCK, ' ').replace(/<[^>]+>/g, '')));

// Every element with data-verbatim, and the text it shows.
function verbatimElements(html) {
  const found = [];
  const stack = [];
  const tagRe = /<!--[\s\S]*?-->|<(\/?)([a-zA-Z][a-zA-Z0-9-]*)((?:[^>"']|"[^"]*"|'[^']*')*)>/g;
  let m;
  while ((m = tagRe.exec(html))) {
    if (m[0].startsWith('<!--')) continue;
    const [, closing, rawTag, attrs] = m;
    const tag = rawTag.toLowerCase();
    if (VOID.has(tag) || attrs.trim().endsWith('/')) continue;
    if (!closing && (tag === 'script' || tag === 'style')) {
      const end = html.indexOf(`</${tag}`, tagRe.lastIndex);
      tagRe.lastIndex = end < 0 ? html.length : end;
      continue;
    }
    if (!closing) {
      const path = attrs.match(/\sdata-verbatim="([^"]*)"/);
      stack.push({ tag, path: path ? decode(path[1]) : null, start: tagRe.lastIndex });
      continue;
    }
    let i = stack.length - 1;
    while (i >= 0 && stack[i].tag !== tag) i--;
    if (i < 0) continue;
    const el = stack[i];
    stack.length = i;
    if (el.path !== null) found.push({ path: el.path, text: textOf(html.slice(el.start, m.index)) });
  }
  return found;
}

// A path like "drips.iron-infusion.sections.2.body" (drips are found by slug).
function resolve(path) {
  let value = MENU;
  const keys = path.split('.');
  for (let i = 0; i < keys.length; i++) {
    if (value == null) return undefined;
    value = keys[i - 1] === 'drips' && i === 1 ? value.find((d) => d.slug === keys[i]) : value[keys[i]];
  }
  return value;
}

// The strings a treatment page must show.
function requiredFor(drip) {
  const p = `drips.${drip.slug}`;
  const paths = [`${p}.name`, `${p}.priceLabel`, `${p}.description`, 'disclaimer'];
  if (drip.tagline) paths.push(`${p}.tagline`);
  drip.ingredients.forEach((_, i) => paths.push(`${p}.ingredients.${i}`));
  drip.ingredientDescriptions.forEach((_, i) => paths.push(`${p}.ingredientDescriptions.${i}.name`, `${p}.ingredientDescriptions.${i}.text`));
  if (drip.priceTableLabel) paths.push(`${p}.priceTableLabel`);
  if (drip.priceTable) {
    drip.priceTable.columns.forEach((_, i) => paths.push(`${p}.priceTable.columns.${i}`));
    drip.priceTable.rows.forEach((row, r) => row.forEach((_, c) => paths.push(`${p}.priceTable.rows.${r}.${c}`)));
  }
  if (drip.moreInfoIntro) paths.push(`${p}.moreInfoIntro`);
  (drip.sections || []).forEach((_, i) => paths.push(`${p}.sections.${i}.heading`, `${p}.sections.${i}.body`));
  if (drip.pricingNote) paths.push(`${p}.pricingNote`);
  (drip.footnotes || []).forEach((_, i) => paths.push(`${p}.footnotes.${i}`));
  const other = drip.proVariantSlug || drip.baseVariantSlug;
  if (other) paths.push(`drips.${other}.name`, `drips.${other}.priceLabel`);
  if (drip.proVariantSlug) proAdds(drip, bySlug[drip.proVariantSlug]).adds.forEach((a) => paths.push(`drips.${drip.proVariantSlug}.ingredients.${a.i}`));
  return paths;
}

// The strings the glossary must show: every category, entry name and text.
function requiredForGlossary() {
  return ['disclaimer', ...GLOSSARY.flatMap((c) => [`${c.path}.category`, ...c.items.flatMap((item) => [`${item.path}.name`, `${item.path}.text`])])];
}

