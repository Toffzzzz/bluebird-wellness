// Width and height of a WebP file, from its header.
function webpSize(file) {
  const b = readFileSync(at(file));
  if (b.toString('ascii', 0, 4) !== 'RIFF' || b.toString('ascii', 8, 12) !== 'WEBP') return null;
  const chunk = b.toString('ascii', 12, 16);
  if (chunk === 'VP8X') return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
  if (chunk === 'VP8 ') return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  if (chunk === 'VP8L') {
    const n = b.readUInt32LE(21);
    return [1 + (n & 0x3fff), 1 + ((n >> 14) & 0x3fff)];
  }
  return null;
}

function checkedSize(file, declared) {
  if (!existsSync(at(file))) fail(`Missing image: ${file}`);
  const size = webpSize(file);
  if (!size) return declared;
  if (declared && (declared[0] !== size[0] || declared[1] !== size[1])) {
    notes.push(`${file} is ${size[0]} × ${size[1]}, but TREATMENTS says ${declared[0]} × ${declared[1]}; the pages use the file's size.`);
  }
  return size;
}

// The picture, tint and badge of a drip: images/treatments/<slug>.webp if it
// exists, else its own stage treatment's picture, or (for a Pro drip) its
// standard version's; the tint and badge come from the stage treatment. A
// drip with no stage treatment has a new picture or a placeholder.
function visualsFor(drip) {
  const own = TREATMENTS.find((t) => t.menuSlug === drip.slug);
  const stage = own || (drip.baseVariantSlug && TREATMENTS.find((t) => t.menuSlug === drip.baseVariantSlug));
  const extra = NEW_PICTURES[drip.slug];
  const picture = `images/treatments/${drip.slug}.webp`;
  const hasPicture = existsSync(at(picture));
  if (stage) {
    if (!stage.image && !hasPicture) fail(`TREATMENTS entry "${stage.id}" has no image.`);
    const image = hasPicture ? picture : stage.image;
    const same = image === stage.image; // the stage's own image: its size and fit apply
    return {
      image,
      art: LINE_ART[stage.id] ? stage.id : null,
      imageSize: checkedSize(image, same ? stage.imageSize : null),
      imageFit: (same && stage.imageFit) || null,
      alt: extra?.alt || stage.alt || '',
      tint: stage.showcase?.tint || null,
      badge: own?.badge || null,
    };
  }
  if (!extra) fail(`No picture for ${drip.slug}: link it to a TREATMENTS entry (menuSlug) or add it to NEW_PICTURES.`);
  if (hasPicture) {
    if (!extra.alt) notes.push(`${picture} has no alt text yet: add it to NEW_PICTURES in scripts/build-menu.mjs.`);
    return { image: picture, imageSize: checkedSize(picture, null), imageFit: null, alt: extra.alt || '', tint: null, badge: null };
  }
  return { image: null, placeholder: extra.placeholder, tint: null, badge: null };
}

