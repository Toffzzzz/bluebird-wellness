// One list of the drip's ingredients, exactly as written, in the menu's
// order. A line with a description opens to show it; the base solution's
// lines are grouped under it; notes are small print below the list.
function ingredientsHTML(drip, p) {
  if (!drip.ingredients.length && !drip.ingredientDescriptions.length) return '';
  const { rows, notes, unmatched } = ingredientRows(drip);
  const I = '              ';
  const line = (row) => `<span${vb(`${p}.ingredients.${row.i}`)}>${esc(row.line)}</span>`;
  const rowHTML = (row) => {
    const group = row.children.length ? `
${I}  <ul class="ingredients__group">
${row.children.map((child) => `${I}    <li>${line(child)}</li>`).join('\n')}
${I}  </ul>` : '';
    if (!row.desc) return `${I}<li class="ingredients__plain">${line(row)}${group}</li>`;
    return `${I}<li>
${ingredientDetailsHTML(line(row), row.desc, `${p}.ingredientDescriptions.${row.desc.j}`, `${I}  `)}${group}
${I}</li>`;
  };
  const extra = unmatched.map((d) => `${I}<li>
${ingredientDetailsHTML(`<span${vb(`${p}.ingredientDescriptions.${d.j}.name`)}>${esc(d.name)}</span>`, d, `${p}.ingredientDescriptions.${d.j}`, `${I}  `)}
${I}</li>`);
  const hasDetails = rows.some((r) => r.desc) || unmatched.length;
  const toggle = hasDetails
    ? `
            <button type="button" class="btn btn--secondary btn--compact" data-expand-all aria-controls="ingredient-list" hidden>Expand all</button>` : '';
  const small = notes.map((n) => `
          <p class="ingredients__note"${vb(`${p}.ingredients.${n.i}`)}>${esc(n.line)}</p>`).join('');
  return `
    <section class="drip-section" id="ingredients" aria-labelledby="ingredients-title">
      <div class="container">
        <div class="ingredients" data-fade>
          <div class="ingredients__head">
            <h2 class="drip-section__title" id="ingredients-title">Ingredients</h2>${toggle}
          </div>
          <ul class="ingredients__list" id="ingredient-list">
${[...rows.map(rowHTML), ...extra].join('\n')}
          </ul>${small}
          <p class="ingredients__glossary"><a class="link" href="../../ingredients/">Ingredient glossary</a></p>
        </div>
      </div>
    </section>`;
}

