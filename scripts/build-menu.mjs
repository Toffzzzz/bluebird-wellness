// On a standard drip with a Pro version: the "Upgrade to Pro" card, with the
// Pro drip's name, price, what it adds and a link to its page.
function upgradeHTML(drip) {
  const pro = bySlug[drip.proVariantSlug];
  if (!pro) return '';
  const q = `drips.${pro.slug}`;
  const { adds } = proAdds(drip, pro);
  const list = adds.length ? `
            <p class="upgrade__adds-title" id="upgrade-adds">Pro adds</p>
            <ul class="upgrade__adds" aria-labelledby="upgrade-adds">
${adds.map((a) => `              <li${vb(`${q}.ingredients.${a.i}`)}>${esc(a.line)}</li>`).join('\n')}
            </ul>` : '';
  return `
          <aside class="upgrade" aria-labelledby="upgrade-title">
            <p class="eyebrow">Upgrade to Pro</p>
            <h2 class="upgrade__title" id="upgrade-title"><span${vb(`${q}.name`)}>${esc(pro.name)}</span> ${PRO_BADGE}</h2>
            <p class="upgrade__price"${vb(`${q}.priceLabel`)}>${esc(pro.priceLabel)}</p>${list}
            <a class="btn btn--secondary btn--compact" href="../${esc(pro.slug)}/">Learn more<span class="visually-hidden"> about ${esc(pro.name)}</span></a>
          </aside>`;
}

// On a Pro drip: the quiet link back to its standard version.
